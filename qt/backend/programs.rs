fn command(value: &str) -> Option<&'static str> {
    let name = value
        .rsplit(['/', '\\'])
        .next()
        .unwrap_or(value)
        .trim_start_matches('-')
        .to_ascii_lowercase();
    let name = name.strip_suffix(".exe").unwrap_or(&name);
    let lookup = |n: &str| {
        ALIASES
            .iter()
            .find(|(a, _)| *a == n)
            .map(|(_, s)| *s)
            .or_else(|| {
                SLUGS
                    .iter()
                    .copied()
                    .find(|s| *s == n && !NOT_COMMANDS.contains(s))
            })
    };
    lookup(name).or_else(|| {
        lookup(name.trim_end_matches(|c: char| c.is_ascii_digit() || c == '.' || c == '-'))
    })
}
pub fn icon(program: Option<&str>, script: Option<&str>, executable: Option<&str>) -> Value {
    let slug = program
        .and_then(command)
        .or_else(|| {
            script.and_then(|p| {
                SCRIPTS
                    .iter()
                    .find(|(end, _)| {
                        p.strip_suffix(end)
                            .is_some_and(|v| v.is_empty() || v.ends_with('/'))
                    })
                    .map(|(_, s)| *s)
            })
        })
        .or_else(|| executable.and_then(command))
        .unwrap_or("shell");
    let hash = slug
        .bytes()
        .fold(0usize, |v, b| v.wrapping_mul(31).wrapping_add(b as usize));
    let tint = ["#8bc5ff", "#a6dfb4", "#e5b7ef", "#f1cb83", "#93d9dc"][hash % 5];
    let badge = if slug == "shell" {
        ">_".into()
    } else {
        slug.chars()
            .filter(|c| c.is_alphanumeric())
            .take(2)
            .collect::<String>()
            .to_uppercase()
    };
    // Codepoints inspected in the existing font cmap/post tables. Seti/Devicons and
    // Octicons are MIT; Material Design family cues are Apache 2.0 (font README).
    let glyph = match slug {
        "python" | "uv" => "\u{e606}",
        "rust" => "\u{e68b}",
        "node" | "bun" | "pnpm" | "deno" => "\u{e60c}",
        "go" => "\u{e627}",
        "lua" => "\u{e620}",
        "docker" | "podman" | "kubernetes" | "shell-container" => "\u{e650}",
        "git" | "git-changes" | "github" | "gitlab" | "jj" => "\u{f418}",
        "neovim" => "\u{e83a}",
        "vim" => "\u{e7c5}",
        "helix" | "emacs" | "nano" | "kakoune" | "sublime" => "\u{f03eb}",
        "postgres" | "mysql" | "sqlite" | "redis" | "dbcli" => "\u{f01bc}",
        "claude-code" | "codex" | "copilot" | "cursor" | "gemini" | "amp" | "aider" | "pi"
        | "mistral" => "\u{f06a9}",
        s if s.starts_with("shell") => "\u{f489}",
        _ => "\u{f0169}",
    };
    json!({"glyph":glyph,"slug":slug,"name":slug.replace('-'," "),"badge":badge,"tint":tint})
}
